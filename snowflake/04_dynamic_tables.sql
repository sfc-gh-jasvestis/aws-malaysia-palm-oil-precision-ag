-- Alerts fire on the bottom tail of FFB Yield (Avg)
-- (lower is worse for this metric).
CREATE OR REPLACE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = '30 days' WAREHOUSE = TOURISM_WH
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH thresh AS (
  SELECT PERCENTILE_CONT(0.09) WITHIN GROUP (ORDER BY KPI_FFB_YIELD_AVG) AS T
  FROM RAW.SENSOR_READINGS
)
SELECT
  e.ID AS ENTITY_ID,
  e.NAME AS ENTITY_NAME,
  e.REGION,
  e.CATEGORY,
  e.STATUS,
  COUNT(*) AS EVENT_COUNT,
  SUM(CASE WHEN f.KPI_FFB_YIELD_AVG <= (SELECT T FROM thresh) THEN 1 ELSE 0 END) AS ALERT_COUNT,
  ROUND(AVG(f.KPI_FFB_YIELD_AVG), 2) AS AVG_FFB_YIELD,
  ROUND(AVG(f.KPI_OER_RATE), 2) AS AVG_OER_RATE,
  ROUND(AVG(f.KPI_HARVEST_INTERVAL), 2) AS AVG_HARVEST_INTERVAL,
  ROUND(AVG(f.KPI_PALM_AGE_AVG), 2) AS AVG_PALM_AGE,
  ROUND(AVG(f.KPI_FERTILIZER_COST), 2) AS AVG_FERTILIZER_COST
FROM RAW.SENSOR_READINGS f
JOIN RAW.FELDA_BENCHMARKS e ON e.ID = f.ENTITY_ID
CROSS JOIN thresh
GROUP BY e.ID, e.NAME, e.REGION, e.CATEGORY, e.STATUS;

