-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT blk.ID AS ENTITY_ID, blk.NAME AS ENTITY_NAME,
       blk.REGION, blk.CATEGORY, blk.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(o.CROP_LOSS_COUNT) AS CROP_LOSS_COUNT,
       SUM(o.OPERATING_HOURS) AS OPERATING_HOURS, SUM(o.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(o.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(o.SCOUTING_DUE) AS SCOUTING_DUE, SUM(o.SCOUTING_DONE) AS SCOUTING_DONE,
       SUM(o.FFB_TONNES) AS FFB_TONNES, SUM(o.FERTILIZER_KG) AS FERTILIZER_KG,
       SUM(o.RIPE_BUNCHES) AS RIPE_BUNCHES, SUM(o.BUNCHES_GRADED) AS BUNCHES_GRADED,
       SUM(o.PEST_ALERTS) AS PEST_ALERTS,
       100.0 * SUM(o.RIPE_BUNCHES) / NULLIF(SUM(o.BUNCHES_GRADED), 0) AS RIPE_PCT,
       SUM(o.FERTILIZER_KG) / NULLIF(SUM(o.FFB_TONNES), 0) AS FERT_KG_PER_T,
       100.0 * SUM(o.OPERATING_HOURS) / NULLIF(SUM(o.PLANNED_HOURS), 0) AS SENSOR_UPTIME_PCT,
       100.0 * SUM(o.SCOUTING_DONE) / NULLIF(SUM(o.SCOUTING_DUE), 0) AS SCOUTING_COMPLETION_PCT,
       MAX(o.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.BLOCK_DAILY o
JOIN RAW.BLOCKS blk ON blk.ID = o.ENTITY_ID
GROUP BY blk.ID, blk.NAME, blk.REGION, blk.CATEGORY, blk.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(RIPE_BUNCHES) AS RIPE_BUNCHES, SUM(BUNCHES_GRADED) AS BUNCHES_GRADED,
       SUM(FFB_TONNES) AS FFB_TONNES, SUM(FERTILIZER_KG) AS FERTILIZER_KG,
       SUM(PEST_ALERTS) AS PEST_ALERTS, SUM(CROP_LOSS_COUNT) AS CROP_LOSS_COUNT,
       100.0 * SUM(RIPE_BUNCHES) / NULLIF(SUM(BUNCHES_GRADED), 0) AS RIPE_PCT,
       SUM(FERTILIZER_KG) / NULLIF(SUM(FFB_TONNES), 0) AS FERT_KG_PER_T
FROM RAW.BLOCK_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.CROP_LOSS_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(CROP_LOSS_COUNT) AS CROP_LOSS_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(BUNCHES_GRADED) - SUM(RIPE_BUNCHES) AS UNRIPE_BUNCHES
FROM RAW.BLOCK_DAILY
WHERE CROP_LOSS_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(RIPE_BUNCHES) AS RIPE_BUNCHES, SUM(BUNCHES_GRADED) AS BUNCHES_GRADED,
         SUM(FFB_TONNES) AS FFB_TONNES, SUM(FERTILIZER_KG) AS FERTILIZER_KG,
         SUM(PEST_ALERTS) AS PEST_ALERTS, SUM(CROP_LOSS_COUNT) AS CROP_LOSSES,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.BLOCK_DAILY
), blocks AS (SELECT COUNT(*) AS BLOCK_COUNT FROM RAW.BLOCKS),
coverage AS (
  SELECT 100.0 * SUM(LEAST(MAPPED_HA, BLOCK_HA)) / NULLIF(SUM(BLOCK_HA), 0) AS MAPPED_PCT
  FROM RAW.SENSOR_COVERAGE
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Ripe Bunch Rate' AS TITLE,
         100.0 * RIPE_BUNCHES / NULLIF(BUNCHES_GRADED, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Crop-Loss Events', CROP_LOSSES, '' FROM observations
  UNION ALL SELECT 3, 'Fertilizer Intensity', FERTILIZER_KG / NULLIF(FFB_TONNES, 0), ' kg/t FFB' FROM observations
  UNION ALL SELECT 4, 'FFB Harvested (t)', FFB_TONNES, '' FROM observations
  UNION ALL SELECT 5, 'Sensor Network Uptime', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Blocks Monitored', BLOCK_COUNT, '' FROM blocks
  UNION ALL SELECT 7, 'Sensor Mapping Coverage', MAPPED_PCT, '%' FROM coverage
  UNION ALL SELECT 8, 'Pest Alerts', PEST_ALERTS, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.CROP_LOSS_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
