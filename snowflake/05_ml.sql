-- Crop-loss risk scoring and FFB harvest forecast over the synthetic snapshot.
-- Predicts P(crop-loss event in the next 7 days) per block and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.CROP_LOSS_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.MOISTURE_DEFICIT_MM, r.DRAIN_LEVEL_PCT,
       AVG(r.MOISTURE_DEFICIT_MM) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS MOISTURE_DEFICIT_7D,
       SUM(r.CROP_LOSS_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS CROP_LOSSES_30D,
       IFF(SUM(r.CROP_LOSS_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'CROP_LOSS', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.BLOCK_DAILY r JOIN RAW.BLOCKS t ON t.ID = r.ENTITY_ID
-- Regional weather events are not block-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Prolonged dry spell', 'Flash flood waterlogging') OR r.CROP_LOSS_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.CROP_LOSS_TRAIN AS
SELECT CATEGORY, AGE_YEARS, MOISTURE_DEFICIT_MM, DRAIN_LEVEL_PCT, MOISTURE_DEFICIT_7D, CROP_LOSSES_30D, LABEL
FROM ML.CROP_LOSS_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.CROP_LOSS_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, MOISTURE_DEFICIT_MM, DRAIN_LEVEL_PCT, MOISTURE_DEFICIT_7D, CROP_LOSSES_30D, LABEL
FROM ML.CROP_LOSS_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.CROP_LOSS_RISK_MODEL(
  INPUT_DATA => TABLE(ML.CROP_LOSS_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.CROP_LOSS_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.CROP_LOSS_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'MOISTURE_DEFICIT_MM', MOISTURE_DEFICIT_MM,
           'DRAIN_LEVEL_PCT', DRAIN_LEVEL_PCT, 'MOISTURE_DEFICIT_7D', MOISTURE_DEFICIT_7D, 'CROP_LOSSES_30D', CROP_LOSSES_30D)):probability:CROP_LOSS::FLOAT AS P
  FROM ML.CROP_LOSS_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'CROP_LOSS', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'CROP_LOSS', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'CROP_LOSS', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'CROP_LOSS', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per block (label unknown, so excluded from features).
CREATE TABLE ML.CROP_LOSS_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.CROP_LOSS_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.CROP_LOSS_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'MOISTURE_DEFICIT_MM', MOISTURE_DEFICIT_MM,
           'DRAIN_LEVEL_PCT', DRAIN_LEVEL_PCT, 'MOISTURE_DEFICIT_7D', MOISTURE_DEFICIT_7D, 'CROP_LOSSES_30D', CROP_LOSSES_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:CROP_LOSS::FLOAT, 4) AS CROP_LOSS_PROB_7D,
       CASE WHEN P:probability:CROP_LOSS::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:CROP_LOSS::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Grower-wide daily FFB harvest forecast (14 days, tonnes) from the daily series.
CREATE VIEW ML.DAILY_FFB AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(FFB_TONNES)::FLOAT AS FFB_TONNES
FROM RAW.BLOCK_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.FFB_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_FFB),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'FFB_TONNES'
);

CREATE TABLE ML.FFB_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST, 1) AS FFB_TONNES,
       ROUND(GREATEST(0, LOWER_BOUND), 1) AS LOWER_BOUND, ROUND(UPPER_BOUND, 1) AS UPPER_BOUND
FROM TABLE(ML.FFB_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
